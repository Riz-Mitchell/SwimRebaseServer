using Ai.Domain.Models;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Ai.Infrastructure.Configurations;

public sealed class UploadedImageConfiguration : IEntityTypeConfiguration<UploadedImage>
{
    public void Configure(EntityTypeBuilder<UploadedImage> builder)
    {
        builder.ToTable("uploaded_images");
        builder.HasKey(i => i.Id);

        builder.Property(i => i.ObjectKey).HasMaxLength(500).IsRequired();
        builder.Property(i => i.ContentType).HasMaxLength(100).IsRequired();
        builder.Property(i => i.Status).HasConversion<string>().HasMaxLength(20).IsRequired();
        builder.Property(i => i.CreatedAt).IsRequired();

        // Object keys are generated by us (never user input) and are unique per image by construction,
        // but the index also backs a defensive lookup-by-key if that's ever needed.
        builder.HasIndex(i => i.ObjectKey).IsUnique();

        // Scoped ownership lookup - every read of an UploadedImage is by (userId, id).
        builder.HasIndex(i => new { i.UserId, i.Id });
    }
}
